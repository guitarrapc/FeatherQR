using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using FeatherQR.Gs1.Internals;
using QRInteropFixtures;

namespace FeatherQR.Tests;

/// <summary>
/// Renders <c>src/FeatherQR.Gs1/Internals/Gs1AiTable.Generated.cs</c> and <c>Gs1CodeLists.Generated.cs</c> from
/// the pinned Syntax Dictionary release and its reference linters. The byte layouts are the ones
/// <c>Gs1AiTable</c> and <c>Gs1CodeLists</c> read, documented there. Everything is deterministic, so the same
/// inputs render the same text, which is what the drift test compares.
/// </summary>
public static class Gs1AiTableGenerator
{
    private const string DictionaryCommit = "8ad003f83a4ba6c2179ce15d578fae27d6580909";

    private static readonly string[] ListLinters = ["iso3166", "iso3166alpha2", "iso4217", "mediatype", "packagetype"];

    /// <summary>The generated files as (repository-relative path, text with LF line endings).</summary>
    public static (string Path, string Text)[] Render(string dictionaryPath, string sourceDir)
    {
        var dictionary = new Gs1SyntaxDictionary(dictionaryPath);
        return
        [
            ("src/FeatherQR.Gs1/Internals/Gs1AiTable.Generated.cs", RenderTable(dictionary)),
            ("src/FeatherQR.Gs1/Internals/Gs1CodeLists.Generated.cs", RenderLists(dictionary.Release, sourceDir)),
        ];
    }

    private static string Header(string release, string sources) =>
        $"""
        // <auto-generated>
        //   Generated by Gs1AiTableGeneratorTest from the GS1 Barcode Syntax Dictionary, release {release}
        //   (https://github.com/gs1/gs1-syntax-dictionary, commit {DictionaryCommit}, Apache License 2.0; see THIRD-PARTY-NOTICES.md).
        //   Source: {sources}, committed under tests/FeatherQR.Tests/Fixtures/Gs1/syntax-dictionary/ with PROVENANCE.md.
        //   Do not edit by hand. Run the test outside CI to regenerate, and review the diff.
        // </auto-generated>

        namespace FeatherQR.Gs1.Internals;

        """;

    private static string RenderTable(Gs1SyntaxDictionary dictionary)
    {
        var linterBits = Enum.GetValues<Gs1Linter>().ToDictionary(l => l.ToString().ToLowerInvariant(), l => (int)l, StringComparer.Ordinal);
        foreach (var name in dictionary.Linters)
        {
            if (!linterBits.ContainsKey(name))
                throw new InvalidDataException($"The dictionary names linter '{name}', which Gs1Linter does not implement. Add the linter before pinning this release.");
        }

        var components = new List<byte>();
        var componentOffsets = new Dictionary<string, int>(StringComparer.Ordinal);
        var attributes = new List<byte> { 0 }; // offset 0: an empty qualifier list, shared by keys without qualifiers
        var attributeOffsets = new Dictionary<string, int>(StringComparer.Ordinal);

        var entries = dictionary.Entries
            .Select(e => (Entry: e, FirstKey: Key(e.FirstAi), LastKey: Key(e.LastAi)))
            .OrderBy(e => e.FirstKey)
            .ToList();
        for (var i = 1; i < entries.Count; i++)
        {
            if (entries[i].FirstKey <= entries[i - 1].LastKey)
                throw new InvalidDataException($"Entries {entries[i - 1].Entry.FirstAi} and {entries[i].Entry.FirstAi} overlap.");
        }

        var entryBytes = new List<byte>();
        foreach (var (entry, firstKey, lastKey) in entries)
        {
            if (entry.Components.Length == 0 || entry.Components.Length > 255)
                throw new InvalidDataException($"Entry {entry.FirstAi} has {entry.Components.Length} components.");
            var componentOffset = Intern(components, componentOffsets, RenderComponents(entry.Components, linterBits), 11, "component");
            var reqOffset = entry.Req.Length == 0 ? 0xFFFF : Intern(attributes, attributeOffsets, RenderRequisites(entry.Req), 1, "attribute");
            var exOffset = entry.Ex.Length == 0 ? 0xFFFF : Intern(attributes, attributeOffsets, RenderPatterns(entry.Ex.SelectMany(e => e.Split(',')).ToArray()), 1, "attribute");
            var dlOffset = entry.DlPKey is null ? 0xFFFF : entry.DlPKey.Length == 0 ? 0 : Intern(attributes, attributeOffsets, RenderQualifierSequences(entry.DlPKey), 1, "attribute");
            var exCount = entry.Ex.Sum(e => e.Split(',').Length);

            var flags = (entry.PredefinedLength ? 1 : 0) | (entry.DlAttribute ? 2 : 0) | (entry.DlPKey is not null ? 4 : 0);
            AddUInt16(entryBytes, firstKey);
            AddUInt16(entryBytes, lastKey);
            entryBytes.Add((byte)flags);
            entryBytes.Add((byte)entry.Components.Length);
            AddUInt16(entryBytes, componentOffset);
            AddUInt16(entryBytes, reqOffset);
            entryBytes.Add((byte)entry.Req.Length);
            AddUInt16(entryBytes, exOffset);
            entryBytes.Add((byte)exCount);
            AddUInt16(entryBytes, dlOffset);
        }

        var aiCount = dictionary.Ais.Count();
        var sb = new StringBuilder();
        sb.Append(Header(dictionary.Release, "gs1-syntax-dictionary.txt"));
        sb.Append($$"""

            internal static partial class Gs1AiTable
            {
                /// <summary>The Syntax Dictionary release the table was generated from.</summary>
                public const string DictionaryRelease = "{{dictionary.Release}}";

                /// <summary>Entry lines of the dictionary, one per AI or AI range, in key order.</summary>
                public const int EntryCount = {{entries.Count}};

                /// <summary>AIs the release assigns, ranges expanded.</summary>
                public const int AiCount = {{aiCount}};

                // One entry per 16 bytes: first key (u16), last key (u16), flags (predefined 1, Digital Link attribute 2, Digital Link key 4),
                // component count, component offset (u16), requisite offset (u16, 0xFFFF none), requisite group count,
                // exclusion offset (u16, 0xFFFF none), exclusion count, qualifier-sequences offset (u16, 0xFFFF when not a key).
                private static ReadOnlySpan<byte> Entries =>
                [
            {{RenderBytes(entryBytes, 16)}}
                ];

                // One component per 11 bytes: type (0 N, 1 X, 2 Y, 3 Z, bit 7 optional), minimum length, maximum length, linter mask (u64).
                // Identical specifications share one run.
                private static ReadOnlySpan<byte> Components =>
                [
            {{RenderBytes(components, 11)}}
                ];

                // Requisite groups ([alternatives] then per alternative [members] and members as key u16 + wildcard mask),
                // exclusion lists (members only) and qualifier sequences ([sequences] then per sequence [count] and keys u16),
                // each stored once. Offset 0 holds the empty sequence list.
                private static ReadOnlySpan<byte> Attributes =>
                [
            {{RenderBytes(attributes, 24)}}
                ];
            }

            """);
        return sb.ToString().Replace("\r\n", "\n");
    }

    private static string RenderLists(string release, string sourceDir)
    {
        var iso3166 = ReadBitField(Path.Combine(sourceDir, "lint_iso3166.c"), "iso3166", 1000, 64);
        var alpha2 = ReadBitField(Path.Combine(sourceDir, "lint_iso3166alpha2.c"), "iso3166alpha2", 26 * 26, 64);
        var iso4217 = ReadBitField(Path.Combine(sourceDir, "lint_iso4217.c"), "iso4217", 1000, 64);
        var media = ReadBitField(Path.Combine(sourceDir, "lint_mediatype.c"), "mediatypes", 100, 8);
        var packageTypes = ReadStringList(Path.Combine(sourceDir, "lint_packagetype.c"), "packagetypes");

        if (iso3166.Count(b => b) != 249)
            throw new InvalidDataException($"ISO 3166 numeric list has {iso3166.Count(b => b)} codes, expected 249.");
        if (packageTypes.Length != 431 || packageTypes.Any(p => p.Length is 0 or > 4 || !p.All(c => char.IsAsciiDigit(c) || char.IsAsciiLetterUpper(c))))
            throw new InvalidDataException($"Package type list has {packageTypes.Length} codes or a malformed code.");
        var sorted = packageTypes.OrderBy(p => p, StringComparer.Ordinal).ToArray();
        if (!sorted.SequenceEqual(packageTypes, StringComparer.Ordinal))
            throw new InvalidDataException("Package type list is not in ordinal order; the reference binary-searches it.");

        var packageBytes = new List<byte>();
        foreach (var code in sorted)
        {
            for (var i = 0; i < 4; i++)
                packageBytes.Add(i < code.Length ? (byte)code[i] : (byte)0);
        }

        var sb = new StringBuilder();
        sb.Append(Header(release, string.Join(", ", ListLinters.Select(l => $"lint_{l}.c"))));
        sb.Append($$"""

            internal static partial class Gs1CodeLists
            {
                /// <summary>Package type codes in the list.</summary>
                public const int PackageTypeCount = {{sorted.Length}};

                // Bit fields: bit i of the list is bit (i & 7) of byte (i >> 3), least significant bit first.
                private static ReadOnlySpan<byte> Iso3166Numeric =>
                [
            {{RenderBytes(Pack(iso3166), 25)}}
                ];

                private static ReadOnlySpan<byte> Iso3166Alpha2 =>
                [
            {{RenderBytes(Pack(alpha2), 26)}}
                ];

                private static ReadOnlySpan<byte> Iso4217 =>
                [
            {{RenderBytes(Pack(iso4217), 25)}}
                ];

                private static ReadOnlySpan<byte> MediaTypes =>
                [
            {{RenderBytes(Pack(media), 13)}}
                ];

                // Package types, 4 bytes each, zero-padded, in ordinal order.
                private static ReadOnlySpan<byte> PackageTypes =>
                [
            {{RenderBytes(packageBytes, 16)}}
                ];
            }

            """);
        return sb.ToString().Replace("\r\n", "\n");
    }

    private static byte[] RenderComponents(QRInteropFixtures.Gs1Component[] components, Dictionary<string, int> linterBits)
    {
        var bytes = new List<byte>();
        foreach (var component in components)
        {
            var type = component.Type switch { 'N' => 0, 'X' => 1, 'Y' => 2, 'Z' => 3, _ => throw new InvalidDataException($"Component type {component.Type}") };
            if (component.Optional)
                type |= 0x80;
            if (component.Min > 255 || component.Max > 255)
                throw new InvalidDataException("A component length does not fit a byte.");
            bytes.Add((byte)type);
            bytes.Add((byte)component.Min);
            bytes.Add((byte)component.Max);
            var mask = 0UL;
            foreach (var linter in component.Linters)
                mask |= 1UL << linterBits[linter];
            for (var i = 0; i < 8; i++)
                bytes.Add((byte)(mask >> (8 * i)));
        }
        return bytes.ToArray();
    }

    /// <summary>Each <c>req=</c> attribute is a group: [alternatives], then per alternative [members] and the members.</summary>
    private static byte[] RenderRequisites(string[] req)
    {
        var bytes = new List<byte>();
        foreach (var group in req)
        {
            var alternatives = group.Split(',');
            bytes.Add((byte)alternatives.Length);
            foreach (var alternative in alternatives)
            {
                var members = alternative.Split('+');
                bytes.Add((byte)members.Length);
                bytes.AddRange(RenderPatterns(members));
            }
        }
        return bytes.ToArray();
    }

    private static byte[] RenderPatterns(string[] patterns)
    {
        var bytes = new List<byte>();
        foreach (var pattern in patterns)
        {
            if (pattern.Length < 2 || pattern.Length > 4 || !pattern.All(c => char.IsAsciiDigit(c) || c == 'n'))
                throw new InvalidDataException($"Not an AI pattern: {pattern}");
            var wildcards = 0;
            var value = 0;
            for (var i = 0; i < pattern.Length; i++)
            {
                value *= 10;
                if (pattern[i] == 'n')
                    wildcards |= 1 << i;
                else
                    value += pattern[i] - '0';
            }
            AddUInt16(bytes, pattern.Length * 10000 + value);
            bytes.Add((byte)wildcards);
        }
        return bytes.ToArray();
    }

    /// <summary><c>dlpkey=22,10,21|235</c>: [sequences], then per sequence [count] and the keys as u16.</summary>
    private static byte[] RenderQualifierSequences(string dlpkey)
    {
        var bytes = new List<byte>();
        var sequences = dlpkey.Split('|');
        bytes.Add((byte)sequences.Length);
        foreach (var sequence in sequences)
        {
            var keys = sequence.Split(',');
            bytes.Add((byte)keys.Length);
            foreach (var key in keys)
                AddUInt16(bytes, Key(key));
        }
        return bytes.ToArray();
    }

    private static int Key(string ai)
    {
        if (ai.Length < 2 || ai.Length > 4 || !ai.All(char.IsAsciiDigit))
            throw new InvalidDataException($"Not an AI: {ai}");
        return ai.Length * 10000 + int.Parse(ai, CultureInfo.InvariantCulture);
    }

    /// <summary>Appends a byte run once and returns its offset, sharing an identical run already appended. Offsets are in bytes and must fit a u16.</summary>
    private static int Intern(List<byte> pool, Dictionary<string, int> offsets, byte[] run, int alignment, string what)
    {
        var text = Convert.ToHexString(run);
        if (offsets.TryGetValue(text, out var offset))
            return offset;
        offset = pool.Count;
        if (offset % alignment != 0)
            throw new InvalidOperationException($"The {what} pool is misaligned at {offset}.");
        if (offset + run.Length > 0xFFFE)
            throw new InvalidDataException($"The {what} pool exceeds a u16 offset.");
        pool.AddRange(run);
        offsets[text] = offset;
        return offset;
    }

    private static void AddUInt16(List<byte> bytes, int value)
    {
        if ((uint)value > 0xFFFF)
            throw new InvalidDataException($"{value} does not fit a u16.");
        bytes.Add((byte)value);
        bytes.Add((byte)(value >> 8));
    }

    private static byte[] Pack(bool[] bits)
    {
        var bytes = new byte[(bits.Length + 7) / 8];
        for (var i = 0; i < bits.Length; i++)
        {
            if (bits[i])
                bytes[i >> 3] |= (byte)(1 << (i & 7));
        }
        return bytes;
    }

    /// <summary>
    /// The C bit field of a reference linter: the <c>0b…</c> literals of its <c>static const</c> array, which the
    /// linter indexes most significant bit first (<c>GS1_LINTER_BITFIELD_LOOKUP</c>), read as bits 0.. of the list.
    /// </summary>
    private static bool[] ReadBitField(string path, string arrayName, int bitCount, int wordBits)
    {
        var source = File.ReadAllText(path).Replace("\r\n", "\n");
        var start = source.IndexOf($" {arrayName}[] = {{", StringComparison.Ordinal);
        if (start < 0)
            throw new InvalidDataException($"{Path.GetFileName(path)} has no array {arrayName}.");
        var end = source.IndexOf("#else", start, StringComparison.Ordinal);
        var block = source.Substring(start, end - start);
        var words = Regex.Matches(block, @"0b([01]+)").Select(m => m.Groups[1].Value).ToArray();
        if (words.Length * wordBits < bitCount || words.Any(w => w.Length != wordBits))
            throw new InvalidDataException($"{Path.GetFileName(path)}: {words.Length} words of {wordBits} bits for {bitCount} bits.");
        var bits = new bool[bitCount];
        for (var i = 0; i < bitCount; i++)
            bits[i] = words[i / wordBits][i % wordBits] == '1';
        // Bits past the list's end must be clear, or the list is wider than the linter says.
        for (var i = bitCount; i < words.Length * wordBits; i++)
        {
            if (words[i / wordBits][i % wordBits] == '1')
                throw new InvalidDataException($"{Path.GetFileName(path)}: bit {i} is set past the {bitCount}-bit list.");
        }
        return bits;
    }

    private static string[] ReadStringList(string path, string arrayName)
    {
        var source = File.ReadAllText(path).Replace("\r\n", "\n");
        var start = source.IndexOf($" {arrayName}[][4] = {{", StringComparison.Ordinal);
        if (start < 0)
            throw new InvalidDataException($"{Path.GetFileName(path)} has no array {arrayName}.");
        var end = source.IndexOf("};", start, StringComparison.Ordinal);
        return Regex.Matches(source.Substring(start, end - start), "\"([A-Z0-9]{1,4})\"").Select(m => m.Groups[1].Value).ToArray();
    }

    private static string RenderBytes(IReadOnlyList<byte> bytes, int perLine)
    {
        var sb = new StringBuilder();
        for (var i = 0; i < bytes.Count; i += perLine)
        {
            sb.Append("        ");
            var line = Math.Min(perLine, bytes.Count - i);
            for (var j = 0; j < line; j++)
            {
                sb.Append("0x").Append(bytes[i + j].ToString("X2", CultureInfo.InvariantCulture)).Append(',');
                if (j < line - 1)
                    sb.Append(' ');
            }
            sb.Append('\n');
        }
        return sb.ToString().TrimEnd('\n');
    }
